`timescale 1ns / 1ps

module DATA_MEMORY_tb;

//=====================================================
// Inputs
//=====================================================

reg clk;
reg MemRead;
reg MemWrite;

reg [31:0] address;
reg [31:0] write_data;

//=====================================================
// Outputs
//=====================================================

wire [31:0] read_data;

//=====================================================
// Instantiate
//=====================================================

DATA_MEMORY uut(

    .clk(clk),

    .MemRead(MemRead),
    .MemWrite(MemWrite),

    .address(address),
    .write_data(write_data),

    .read_data(read_data)

);

//=====================================================
// Clock
//=====================================================

always #5 clk = ~clk;

//=====================================================
// Test Sequence
//=====================================================

initial
begin

    clk = 0;

    MemRead  = 0;
    MemWrite = 0;

    address = 32'd0;
    write_data = 32'd0;

    //-------------------------------------------------
    // Store 100 at address 0
    //-------------------------------------------------

    #10;

    MemWrite = 1;
    address = 32'd0;
    write_data = 32'd100;

    #10;

    MemWrite = 0;

    //-------------------------------------------------
    // Read address 0
    //-------------------------------------------------

    MemRead = 1;
    address = 32'd0;

    #10;

    //-------------------------------------------------
    // Store 555 at address 4
    //-------------------------------------------------

    MemRead = 0;
    MemWrite = 1;

    address = 32'd4;
    write_data = 32'd555;

    #10;

    MemWrite = 0;

    //-------------------------------------------------
    // Read address 4
    //-------------------------------------------------

    MemRead = 1;
    address = 32'd4;

    #10;

    //-------------------------------------------------
    // Read address 8 (should be zero)
    //-------------------------------------------------

    address = 32'd8;

    #10;

    MemRead = 0;

    #10;

    $finish;

end

//=====================================================
// Monitor
//=====================================================

initial
begin

$display("---------------------------------------------------------------------");
$display("Time\tAddr\tMemRead\tMemWrite\tWriteData\tReadData");
$display("---------------------------------------------------------------------");

$monitor("%0t\t%d\t%b\t%b\t\t%d\t\t%d",

         $time,
         address,
         MemRead,
         MemWrite,
         write_data,
         read_data);

end

endmodule
