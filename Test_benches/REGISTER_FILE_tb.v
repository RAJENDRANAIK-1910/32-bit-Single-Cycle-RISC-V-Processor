`timescale 1ns / 1ps

module REGISTER_FILE_tb;

//=====================================================
// Inputs
//=====================================================

reg clk;
reg RegWrite;

reg [4:0] rs1;
reg [4:0] rs2;
reg [4:0] rd;

reg [31:0] write_data;

//=====================================================
// Outputs
//=====================================================

wire [31:0] read_data1;
wire [31:0] read_data2;

//=====================================================
// Instantiate Register File
//=====================================================

REGISTER_FILE uut(

    .clk(clk),
    .RegWrite(RegWrite),

    .rs1(rs1),
    .rs2(rs2),
    .rd(rd),

    .write_data(write_data),

    .read_data1(read_data1),
    .read_data2(read_data2)

);

//=====================================================
// Clock Generation
//=====================================================

always #5 clk = ~clk;

//=====================================================
// Test Sequence
//=====================================================

initial
begin

    clk = 0;

    RegWrite = 0;
    rs1 = 0;
    rs2 = 0;
    rd = 0;
    write_data = 0;

    //-------------------------------------------------
    // Write x1 = 5
    //-------------------------------------------------

    #10;
    RegWrite = 1;
    rd = 5'd1;
    write_data = 32'd5;

    #10;

    //-------------------------------------------------
    // Write x2 = 10
    //-------------------------------------------------

    rd = 5'd2;
    write_data = 32'd10;

    #10;

    //-------------------------------------------------
    // Disable Write
    //-------------------------------------------------

    RegWrite = 0;

    //-------------------------------------------------
    // Read x1 and x2
    //-------------------------------------------------

    rs1 = 5'd1;
    rs2 = 5'd2;

    #20;

    //-------------------------------------------------
    // Attempt to Write x0 (Ignored)
    //-------------------------------------------------

    RegWrite = 1;
    rd = 5'd0;
    write_data = 32'd999;

    #10;

    RegWrite = 0;
    rs1 = 5'd0;

    #20;

    $finish;

end

//=====================================================
// Monitor
//=====================================================

initial
begin

$display("--------------------------------------------------------------------------");
$display("Time\tRegWrite\tRS1\tRS2\tRD\tWrite\tRead1\tRead2");
$display("--------------------------------------------------------------------------");

$monitor("%0t\t%b\t\t%d\t%d\t%d\t%d\t%d\t%d",

         $time,
         RegWrite,
         rs1,
         rs2,
         rd,
         write_data,
         read_data1,
         read_data2);

end

endmodule
