`timescale 1ns / 1ps

module TOP_MODULE_tb;

//=====================================================
// Inputs
//=====================================================

reg clk;
reg reset;

//=====================================================
// Instantiate CPU
//=====================================================

TOP_MODULE uut(

    .clk(clk),
    .reset(reset)

);

//=====================================================
// Clock Generation
//=====================================================

always #5 clk = ~clk;

//=====================================================
// Test Sequence
//=====================================================

initial
begin

    clk   = 0;
    reset = 1;

    // Apply Reset
    #20;
    reset = 0;

    // Run CPU
    #200;

    $finish;

end

//=====================================================
// Monitor
//=====================================================

initial
begin

$display("---------------------------------------------------------------------------------------------------------------");
$display("Time\tPC\t\tInstruction\tALU_Result\tWriteBack\tReadData\tZero");
$display("---------------------------------------------------------------------------------------------------------------");

$monitor("%0t\t%h\t%h\t%h\t%h\t%h\t%b",

         $time,
         uut.pc,
         uut.instruction,
         uut.alu_result,
         uut.write_back_data,
         uut.memory_data,
         uut.Zero);

end

endmodule
