`timescale 1ns / 1ps

module IMMEDIATE_GENERATOR_tb;

reg [31:0] instruction;

wire [31:0] immediate;

//=====================================================
// Instantiate
//=====================================================

IMMEDIATE_GENERATOR uut(

    .instruction(instruction),
    .immediate(immediate)

);

//=====================================================
// Test Sequence
//=====================================================

initial
begin

    //-------------------------------------------------
    // I-Type : addi x1,x0,5
    //-------------------------------------------------

    instruction = 32'h00500093;
    #10;

    //-------------------------------------------------
    // I-Type : lw x5,0(x0)
    //-------------------------------------------------

    instruction = 32'h00002283;
    #10;

    //-------------------------------------------------
    // S-Type : sw x3,0(x0)
    //-------------------------------------------------

    instruction = 32'h00302023;
    #10;

    //-------------------------------------------------
    // B-Type : beq x5,x3,+8
    //-------------------------------------------------

    instruction = 32'h00328463;
    #10;

    //-------------------------------------------------
    // U-Type : lui x1,0x12345
    //-------------------------------------------------

    instruction = 32'h123450B7;
    #10;

    //-------------------------------------------------
    // U-Type : auipc x1,0x12345
    //-------------------------------------------------

    instruction = 32'h12345097;
    #10;

    //-------------------------------------------------
    // J-Type : jal x0,+8
    //-------------------------------------------------

    instruction = 32'h0080006F;
    #10;

    //-------------------------------------------------
    // Invalid
    //-------------------------------------------------

    instruction = 32'hFFFFFFFF;
    #10;

    $finish;

end

//=====================================================
// Monitor
//=====================================================

initial
begin

$display("---------------------------------------------------------------");
$display("Time\tInstruction\tImmediate");
$display("---------------------------------------------------------------");

$monitor("%0t\t%h\t%h",

         $time,
         instruction,
         immediate);

end

endmodule
